-- V1__init.sql - Phase 4 schema init
-- Sử dụng syntax chuẩn tương thích PostgreSQL + H2 (PostgreSQL mode).
-- "BIGSERIAL" của Postgres = "BIGINT IDENTITY" của H2 (mode PostgreSQL-compatible).

-- Leaderboard: lưu điểm best của mỗi player trên từng map.
CREATE TABLE leaderboard (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_name  VARCHAR(50)  NOT NULL,
    map_id       VARCHAR(30)  NOT NULL,
    score        INTEGER      NOT NULL,
    time_seconds INTEGER      NOT NULL DEFAULT 0,
    hp_remain    INTEGER      DEFAULT 0,
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT leaderboard_unique UNIQUE (player_name, map_id)
);

-- Match result: lưu lịch sử trận, mỗi trận 1 row (sẽ phát triển Phase 5+).
CREATE TABLE match_result (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id   VARCHAR(80),
    player_name  VARCHAR(50),
    map_id       VARCHAR(30),
    mode         VARCHAR(20),
    status       VARCHAR(20),
    score        INTEGER DEFAULT 0,
    time_seconds INTEGER DEFAULT 0,
    hp_remain    INTEGER DEFAULT 0,
    started_at   TIMESTAMP,
    ended_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_leaderboard_map_score ON leaderboard (map_id, score DESC);
CREATE INDEX idx_match_result_map      ON match_result (map_id);
